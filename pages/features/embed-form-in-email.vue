<h2 class="fmstr-cmp-eie-faq__h2" id="fmstr-cmp-eie-faq-h2">Common questions</h2>
</header>

<div class="fmstr-cmp-eie-faq__list">

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Does the form actually submit from inside Gmail?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>The first answer registers as a click and travels through to the form as a pre-filled value. With <strong>Partial Submissions</strong> enabled, that value is captured the moment the click lands, even if the respondent never opens the rest of the form.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Will the buttons look right in Outlook?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>Yes for new Outlook (web and the rebuilt desktop client). Outlook classic on Windows uses Word's HTML engine and may strip rounded corners or background colors, but the click-through always works. Test against Litmus's client matrix before any major campaign.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Can I track who clicked which answer?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>Yes. Every answer button is a tracked link with the respondent's ID baked into the URL. Click data flows back to your form's analytics view. ESPs (Mailchimp, HubSpot) also see the click in their own reports.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">What if someone clicks twice or changes their mind?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>The latest click wins. The pre-filled answer on the form page reflects the most recent button they tapped. They can also change it on the form before submitting.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Why only one question in the email?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>Because every additional question is a reason to delete the email. Inbox attention is measured in seconds. One question, one click, then the form. Multi-question email surveys exist (AMP-for-Email) but render only in Gmail, so they ship lower completion in mixed-audience lists than the one-click pattern.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Will this work with my ESP?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>If your ESP supports custom HTML blocks, which Mailchimp, Brevo, HubSpot, Klaviyo, ConvertKit, and Constant Contact all do, yes. Paste the snippet into a "Code Your Own" or "Custom HTML" content block.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">Can I make the form anonymous?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>Yes. Turn off the hidden ID parameter in the share modal. The form treats the click as a stand-alone submission with no respondent tag. The flip side: you lose pre-fill for any other personalised fields, so use this only when respondent identity is not part of the analysis.</p>
</div>
</details>

<details class="fmstr-cmp-eie-faq__item">
<summary><h3 class="fmstr-cmp-eie-faq__h3">How is this different from sending a survey link?</h3></summary>
<div class="fmstr-cmp-eie-faq__answer">
<p>A link asks the recipient to commit before they know what they are committing to. An inline question shows the first question in the inbox, so the decision is "answer this," not "give us five minutes."</p>
</div>
</details>

